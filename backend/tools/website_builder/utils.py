from pathlib import Path
import shutil


GENERATED_WEBSITES_DIR = Path("generated_websites")


def save_website(
    project_name: str,
    framework: str,
    app: str,
    css: str,
    js: str = "",
):
    """
    Save generated website files (HTML, CSS, and optionally JS).
    """

    project_folder = GENERATED_WEBSITES_DIR / project_name

    project_folder.mkdir(
        parents=True,
        exist_ok=True
    )

    framework_lower = framework.lower()

    if framework_lower == "react":
        app_file = project_folder / "App.jsx"
        css_file = project_folder / "App.css"
        js_file = project_folder / "main.js"
    else:
        app_file = project_folder / "index.html"
        css_file = project_folder / "style.css"
        css_file_alt = project_folder / "styles.css"
        js_file = project_folder / "script.js"

    # Build standalone index.html linking styles.css and script.js if not already present
    has_doctype = app.strip().startswith("<!DOCTYPE") or "<html" in app
    if not has_doctype and framework_lower != "react":
        full_html = f'''<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{project_name}</title>
  <link rel="stylesheet" href="styles.css">
</head>
<body>
{app}
  <script src="script.js"></script>
</body>
</html>'''
        with open(app_file, "w", encoding="utf-8") as file:
            file.write(full_html)
    else:
        with open(app_file, "w", encoding="utf-8") as file:
            file.write(app)

    with open(css_file, "w", encoding="utf-8") as file:
        file.write(css)

    # Also save styles.css so ZIP includes index.html, styles.css, and script.js
    if framework_lower != "react":
        with open(css_file_alt, "w", encoding="utf-8") as file:
            file.write(css)

    with open(js_file, "w", encoding="utf-8") as file:
        file.write(js or "")

    # Write a README
    readme_path = project_folder / "README.md"
    with open(readme_path, "w", encoding="utf-8") as file:
        file.write(
            f"# {project_name}\n\n"
            f"Generated by AI Engineering Workspace Website Builder Studio.\n\n"
            f"### Files included:\n"
            f"- `index.html`: Web application markup and structure\n"
            f"- `styles.css`: Complete styling and theme\n"
            f"- `script.js`: Interactive client-side behavior\n\n"
            f"### How to run:\n"
            f"Open `index.html` directly in any modern browser (Chrome, Firefox, Safari, Edge).\n"
        )

    return project_folder


def create_website_zip(
    project_name: str
):
    """
    Create a ZIP file for the generated website.
    """

    project_folder = GENERATED_WEBSITES_DIR / project_name

    if not project_folder.exists():
        raise FileNotFoundError(
            f"{project_name} does not exist."
        )

    zip_path = GENERATED_WEBSITES_DIR / project_name

    shutil.make_archive(
        str(zip_path),
        "zip",
        project_folder
    )

    return f"{zip_path}.zip"